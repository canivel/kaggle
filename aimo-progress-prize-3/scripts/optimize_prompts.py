EVALUATION_CRITERIA = textwrap.dedent("""\
    ## IMO Math Prompt Evaluation Criteria

    Score each configuration on these axes (1-10 scale):

    1. **Clarity of instructions** (1-10): Does the system prompt clearly tell
       the model what to do? Does it avoid ambiguity? IMO problems need precise
       instructions about output format (\\boxed{} with integer), modular
       arithmetic, and the expected range (0-99999).

    2. **Encouragement of code use** (1-10): The model MUST use Python/sympy to
       solve problems. Prompts that explicitly encourage code-first thinking and
       verification score higher. The tool prompt should mention statefulness,
       print() requirement, and available libraries.

    3. **Verification emphasis** (1-10): Does the prompt encourage the model to
       double-check its answer? On IMO problems, verification catches 10-20% of
       errors. Prompts that tell the model to "verify with a separate computation"
       or "check edge cases" score higher.

    4. **Domain coverage** (1-10): IMO covers algebra, combinatorics, geometry,
       and number theory. Does the prompt help the model recognize which domain
       applies? Generic prompts score lower than those with domain-aware guidance.

    5. **Voting strategy quality** (1-10): For 8 parallel attempts with early_stop,
       how well does the voting strategy select the correct answer? Simple majority
       is weak. Inverse entropy is good. Multi-component entropy is better.
       Strategies that incorporate code execution success are best.

    6. **Time budget efficiency** (1-10): With 50 problems in ~17400 seconds, the
       budget must balance hard vs easy problems. Generous high_timeout with modest
       base_timeout plus early_stop is the proven pattern. Very aggressive budgets
       risk running out of time.

    7. **Risk of regression** (1-10, inverted: 10=lowest risk): Changes that
       differ minimally from the proven top-notebook config carry lower risk.
       Novel prompt styles or untested voting formulas carry higher risk.

    8. **Novel insight** (1-10): Does this config introduce a genuinely new idea
       that could improve accuracy? Pure copies of existing configs score low.
       Targeted additions (e.g., explicit modular arithmetic reminder) score higher.

    Compute an overall score as:
        overall = (0.20 * clarity + 0.20 * code_use + 0.15 * verification
                 + 0.10 * domain + 0.15 * voting + 0.10 * time_budget
                 + 0.05 * risk_inv + 0.05 * novelty)
""")

