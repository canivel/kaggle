# ── Claude Code CLI proposer ──────────────────────────────────

def call_claude(prompt: str, system: str = "", timeout: int = 300) -> str:
    """Call Claude Code CLI with --print flag. No API keys needed."""
    import shutil
    claude_bin = (
        os.environ.get("CLAUDE_BIN")
        or shutil.which("claude")
        or shutil.which("claude.cmd")
        or r"C:\Users\dcani\AppData\Roaming\npm\claude.cmd"
    )
    # Remove CLAUDECODE env var to allow nested sessions
    env = os.environ.copy()
    env.pop("CLAUDECODE", None)
    env.pop("CLAUDE_CODE", None)
    # Pipe prompt via stdin — must use bytes to avoid Windows encoding issues
    cmd = [claude_bin, "--print", "--output-format", "text"]
    if system:
        cmd.extend(["--system-prompt", system[:2000]])
    try:
        result = subprocess.run(
            cmd,
            input=prompt.encode("utf-8"),
            capture_output=True,
            timeout=timeout,
            env=env,
        )
        # Decode output
        result = subprocess.CompletedProcess(
            result.args, result.returncode,
            stdout=result.stdout.decode("utf-8", errors="replace"),
            stderr=result.stderr.decode("utf-8", errors="replace"),
        )
        if result.returncode != 0:
            print(f"  [WARN] Claude CLI exit code {result.returncode}")
            if result.stderr:
                print(f"  stderr: {result.stderr[:300]}")
        return result.stdout.strip()
    except subprocess.TimeoutExpired:
        print(f"  [WARN] Claude CLI timed out after {timeout}s")
        return ""
    except FileNotFoundError:
        print("  [ERROR] 'claude' CLI not found on PATH. Install Claude Code first.")
        sys.exit(1)


