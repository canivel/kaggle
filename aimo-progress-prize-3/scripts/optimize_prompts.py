# ── JSON extraction helpers ────────────────────────────────────

def _extract_json(text: str) -> dict:
    """Extract a JSON object from a response that may contain other text."""
    # Try direct parse first
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # Find JSON object in text
    start = text.find("{")
    if start == -1:
        return _default_scores()

    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                try:
                    result = json.loads(text[start : i + 1])
                    # Ensure overall is computed if missing
                    if "overall" not in result:
                        result["overall"] = _compute_overall(result)
                    return result
                except json.JSONDecodeError:
                    pass
                break

    return _default_scores()


def _extract_json_array(text: str) -> list[dict]:
    """Extract a JSON array from a response."""
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    start = text.find("[")
    if start == -1:
        return []

    depth = 0
    for i in range(start, len(text)):
        if text[i] == "[":
            depth += 1
        elif text[i] == "]":
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(text[start : i + 1])
                except json.JSONDecodeError:
                    pass
                break

    return []


def _default_scores() -> dict:
    return {
        "clarity": 5, "code_use": 5, "verification": 5, "domain": 5,
        "voting": 5, "time_budget": 5, "risk_inv": 5, "novelty": 5,
        "overall": 5.0, "strengths": [], "weaknesses": [],
        "suggestion": "evaluation failed",
    }


def _compute_overall(scores: dict) -> float:
    weights = {
        "clarity": 0.20, "code_use": 0.20, "verification": 0.15,
        "domain": 0.10, "voting": 0.15, "time_budget": 0.10,
        "risk_inv": 0.05, "novelty": 0.05,
    }
    total = 0.0
    for key, w in weights.items():
        total += w * float(scores.get(key, 5))
    return round(total, 4)


# ── Main search loop ──────────────────────────────────────────

def run_search(
    iterations: int,
    candidates_per_iter: int,
    db_path: str,
):
    """Execute the meta-harness prompt optimization loop."""
    db = Kaos(db_path)
    search_id = db.spawn("aimo3-prompt-optimizer", config={
        "type": "prompt_optimization",
        "iterations": iterations,
        "candidates_per_iter": candidates_per_iter,
    })
    db.set_status(search_id, "running")

    archive: list[dict] = []

    print("=" * 70)
    print("META-HARNESS PROMPT OPTIMIZER — AIMO3")
    print("=" * 70)
    print(f"  Iterations: {iterations}")
    print(f"  Candidates per iteration: {candidates_per_iter}")
    print(f"  Seeds: {len(ALL_SEEDS)}")
    print(f"  Database: {db_path}")
    print()

    # ── Step 1: Evaluate seeds ──
    print("--- Evaluating seed configurations ---\n")
    for seed_cfg in ALL_SEEDS:
        print(f"  Evaluating: {seed_cfg.name}")
        t0 = time.time()
        scores = evaluate_config(seed_cfg, archive)
        elapsed = time.time() - t0
        print(f"    overall={scores.get('overall', 0):.2f} ({elapsed:.1f}s)")
        for dim in ["clarity", "code_use", "verification", "domain", "voting", "time_budget"]:
            print(f"      {dim}: {scores.get(dim, '?')}")
        if scores.get("strengths"):
            print(f"    + {scores['strengths'][0]}")
        if scores.get("weaknesses"):
            print(f"    - {scores['weaknesses'][0]}")

        entry = {
            "config": seed_cfg.to_dict(),
            "scores": scores,
            "iteration": 0,
        }
        archive.append(entry)

        # Store in kaos
        name = seed_cfg.name
        db.write(search_id, f"/configs/{name}/config.json",
                 json.dumps(seed_cfg.to_dict(), indent=2).encode())
        db.write(search_id, f"/configs/{name}/scores.json",
                 json.dumps(scores, indent=2).encode())
        print()

    db.checkpoint(search_id, label="seeds-evaluated")

    # ── Step 2: Main optimization loop ──
    for iteration in range(1, iterations + 1):
        print(f"\n{'=' * 70}")
        print(f"ITERATION {iteration}/{iterations}")
        print(f"{'=' * 70}\n")

        # Propose new configs
        print("  Proposing via Claude Code CLI...")
        t0 = time.time()
        new_configs = propose_new_config(archive, iteration, candidates_per_iter)
        propose_time = time.time() - t0
        print(f"  Proposed {len(new_configs)} candidates in {propose_time:.1f}s\n")

        if not new_configs:
            print("  [WARN] No candidates proposed, skipping iteration")
            continue

        # Evaluate each new config
        for cfg in new_configs:
            print(f"  Evaluating: {cfg.name}")
            t0 = time.time()
            scores = evaluate_config(cfg, archive)
            elapsed = time.time() - t0
            print(f"    overall={scores.get('overall', 0):.2f} ({elapsed:.1f}s)")
            for dim in ["clarity", "code_use", "verification", "voting"]:
                print(f"      {dim}: {scores.get(dim, '?')}")
            if scores.get("suggestion"):
                print(f"    suggestion: {scores['suggestion']}")

            entry = {
                "config": cfg.to_dict(),
                "scores": scores,
                "iteration": iteration,
            }
            archive.append(entry)

            # Store in kaos
            name = f"iter{iteration}_{cfg.name}"
            db.write(search_id, f"/configs/{name}/config.json",
                     json.dumps(cfg.to_dict(), indent=2).encode())
            db.write(search_id, f"/configs/{name}/scores.json",
                     json.dumps(scores, indent=2).encode())
            print()

        # Checkpoint
        db.checkpoint(search_id, label=f"iter-{iteration}")

        # Show current leaderboard
        ranked = sorted(archive, key=lambda x: x["scores"].get("overall", 0), reverse=True)
        print("  Current leaderboard:")
        for i, entry in enumerate(ranked[:5]):
            cfg_name = entry["config"]["name"]
            overall = entry["scores"].get("overall", 0)
            it = entry.get("iteration", 0)
            print(f"    #{i+1}: {cfg_name:35s} overall={overall:.2f} (iter {it})")

        # Store leaderboard
        db.set_state(search_id, "current_iteration", iteration)
        db.set_state(search_id, "leaderboard", [
            {"name": e["config"]["name"], "overall": e["scores"].get("overall", 0),
             "iteration": e.get("iteration", 0)}
            for e in ranked
        ])

    # ── Step 3: Final results ──
    print("\n" + "=" * 70)
    print("FINAL RESULTS")
    print("=" * 70)

    ranked = sorted(archive, key=lambda x: x["scores"].get("overall", 0), reverse=True)
    for i, entry in enumerate(ranked):
        cfg = entry["config"]
        scores = entry["scores"]
        overall = scores.get("overall", 0)
        it = entry.get("iteration", 0)
        print(
            f"  #{i+1}: {cfg['name']:35s} overall={overall:.2f} (iter {it}) "
            f"| clar={scores.get('clarity', '?')} code={scores.get('code_use', '?')} "
            f"verif={scores.get('verification', '?')} vote={scores.get('voting', '?')}"
        )

    # Export best config
    best = ranked[0]
    best_cfg = AIMO3Config.from_dict(best["config"])
    export_path = Path(__file__).parent.parent / "data" / "best_config.py"
    export_path.parent.mkdir(parents=True, exist_ok=True)
    export_path.write_text(best_cfg.to_notebook_dict())
    print(f"\nBest config exported to: {export_path}")
    print(f"  Name: {best_cfg.name}")
    print(f"  Overall score: {best['scores'].get('overall', 0):.2f}")
    print(f"  Rationale: {best_cfg.rationale}")

    # Also export as JSON for machine consumption
    json_path = Path(__file__).parent.parent / "data" / "best_config.json"
    json_path.write_text(json.dumps({
        "config": best["config"],
        "scores": best["scores"],
    }, indent=2))
    print(f"  JSON: {json_path}")

    # Store final archive
    db.write(search_id, "/final_archive.json",
             json.dumps(archive, indent=2).encode())
    db.write(search_id, "/best_config.py",
             best_cfg.to_notebook_dict().encode())
    db.complete(search_id)
    db.close()

    print(f"\nAll data saved in {db_path}")
    return best_cfg


def export_best(db_path: str):
    """Export the current best config from an existing database."""
    db = Kaos(db_path)

    # Find the search agent
    agents = db.list_agents()
    search_agents = [a for a in agents if "prompt-optimizer" in a["name"]]
    if not search_agents:
        print("No prompt optimization runs found in database.")
        db.close()
        return

    search_id = search_agents[-1]["agent_id"]
    print(f"Search agent: {search_id[:14]}...")

    # Read the archive
    try:
        archive_data = db.read(search_id, "/final_archive.json")
        archive = json.loads(archive_data.decode())
    except FileNotFoundError:
        print("No final archive found. Run the search first.")
        db.close()
        return

    ranked = sorted(archive, key=lambda x: x["scores"].get("overall", 0), reverse=True)

    print("\nAll configs ranked by score:")
    for i, entry in enumerate(ranked):
        cfg = entry["config"]
        overall = entry["scores"].get("overall", 0)
        it = entry.get("iteration", 0)
        print(f"  #{i+1}: {cfg['name']:35s} overall={overall:.2f} (iter {it})")

    best = ranked[0]
    best_cfg = AIMO3Config.from_dict(best["config"])

    export_path = Path(__file__).parent.parent / "data" / "best_config.py"
    export_path.parent.mkdir(parents=True, exist_ok=True)
    export_path.write_text(best_cfg.to_notebook_dict())
    print(f"\nExported to: {export_path}")
    print(f"\nBest config notebook code:\n")
    print(best_cfg.to_notebook_dict())

    db.close()


# ── CLI ────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="Meta-harness prompt optimizer for AIMO3",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""\
            Examples:
              # Quick 3-iteration run:
              uv run python scripts/optimize_prompts.py --iterations 3

              # Full 10-iteration search with 3 candidates per iteration:
              uv run python scripts/optimize_prompts.py --iterations 10 --candidates 3

              # Export the current best from a previous run:
              uv run python scripts/optimize_prompts.py --export-best

              # Use a custom database path:
              uv run python scripts/optimize_prompts.py --iterations 5 --db my_search.db
        """),
    )
    parser.add_argument(
        "--iterations", type=int, default=5,
        help="Number of propose-evaluate iterations (default: 5)",
    )
    parser.add_argument(
        "--candidates", type=int, default=2,
        help="Candidates to propose per iteration (default: 2)",
    )
    parser.add_argument(
        "--db", default="aimo3-prompt-search.db",
        help="SQLite database path (default: aimo3-prompt-search.db)",
    )
    parser.add_argument(
        "--export-best", action="store_true",
        help="Just export the best config from an existing database",
    )
    args = parser.parse_args()

    if args.export_best:
        export_best(args.db)
    else:
        run_search(
            iterations=args.iterations,
            candidates_per_iter=args.candidates,
            db_path=args.db,
        )


if __name__ == "__main__":
    main()
