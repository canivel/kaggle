class AnchorDriftDslAgent(CachedProgramDslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=8)

    def _build_level_program(self, env):
        del env
        if self._current_level_idx is None:
            raise RuntimeError("Anchor Drift DSL has no current level.")
        return list(LEVEL_PROGRAMS[self._current_level_idx])


AGENT_CLASS = AnchorDriftDslAgent
