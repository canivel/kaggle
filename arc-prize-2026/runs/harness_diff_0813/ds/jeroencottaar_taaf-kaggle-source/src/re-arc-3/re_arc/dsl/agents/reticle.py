class ReticleDslAgent(CachedProgramDslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=len(LEVEL_PROGRAMS))

    def _build_level_program(self, env):
        del env
        level_idx = self._current_level_idx
        if level_idx is None or level_idx >= len(LEVEL_PROGRAMS):
            raise RuntimeError("Reticle DSL requested an unknown level.")
        return [(action_id, {}) for action_id in LEVEL_PROGRAMS[level_idx]]
