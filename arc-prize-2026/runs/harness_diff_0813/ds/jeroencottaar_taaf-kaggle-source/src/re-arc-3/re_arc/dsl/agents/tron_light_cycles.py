class TronLightCyclesDslAgent(CachedProgramDslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=6)

    def _build_level_program(self, env) -> list[tuple[int, dict[str, int]]]:
        level_idx = int(env._game.current_level.get_data("level_idx") or 0)
        plan = _LEVEL_PLANS.get(level_idx)
        if not plan:
            raise RuntimeError(f"tron_light_cycles missing plan for level {level_idx}")
        return [(int(action_id), {}) for action_id in plan]


AGENT_CLASS = TronLightCyclesDslAgent
